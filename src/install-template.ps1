# claude-code-tts - makes Claude Code read its answers aloud on Windows.
#   Natural online voice (edge-tts) with automatic fallback to an offline Windows voice.
#
# Usage:
#   powershell -NoProfile -ExecutionPolicy Bypass -File install.ps1 [options]
#   & ([scriptblock]::Create((irm https://raw.githubusercontent.com/spyrad/claude-code-tts/main/install.ps1))) [options]
#
# Options:
#   -Voice <name>          edge-tts voice, e.g. en-US-AriaNeural, de-DE-KatjaNeural
#                          (default: picked from the Windows display language)
#   -FallbackVoice <name>  offline Windows voice, e.g. "Microsoft Zira Desktop"
#   -OfflineOnly           Windows voice only - no Python, nothing is sent to an online service
#   -StopHotkey <keys>     global key combination that silences a running speech (default CTRL+ALT+S)
#   -ReplayHotkey <keys>   reads the last answer again (default CTRL+ALT+R)
#   -ToggleHotkey <keys>   turns read-aloud on or off (default CTRL+ALT+T)
#   -NoHotkey              do not create the hotkey shortcuts
#   -NoTest                no audible test at the end
#   -Uninstall             remove hooks, files and the shortcuts again
#
# Safe to run repeatedly: existing entries are detected, all other settings stay
# untouched, and settings.json is backed up before it is changed.
# Generated by build.ps1 - edit src/install-template.ps1, not install.ps1.
param(
    [string]$ClaudeDir = (Join-Path $env:USERPROFILE '.claude'),
    [string]$Voice,
    [string]$FallbackVoice,
    [switch]$OfflineOnly,
    [string]$StopHotkey = 'CTRL+ALT+S',
    [string]$ReplayHotkey = 'CTRL+ALT+R',
    [string]$ToggleHotkey = 'CTRL+ALT+T',
    [switch]$NoHotkey,
    [switch]$NoTest,
    [switch]$Uninstall
)

$ErrorActionPreference = 'Stop'
$Utf8NoBom = New-Object Text.UTF8Encoding($false)

$SpeakScript = @'
__SPEAK_SCRIPT__
'@

$EdgeScript = @'
__EDGE_SCRIPT__
'@

$HookMarker = 'speak-last-answer.ps1'
# Start menu links with a global hotkey, each runs one mode of the hook script
$Shortcuts = @(
    @{ Name = 'Claude stop reading.lnk'; Mode = '-Stop'; Key = $StopHotkey; Option = '-StopHotkey'
       Purpose = 'Stop reading'; Description = 'Stops the running Claude Code read-aloud' }
    @{ Name = 'Claude read again.lnk'; Mode = '-Replay'; Key = $ReplayHotkey; Option = '-ReplayHotkey'
       Purpose = 'Read the last answer again'; Description = 'Reads the last Claude Code answer aloud again' }
    @{ Name = 'Claude read-aloud on-off.lnk'; Mode = '-Toggle'; Key = $ToggleHotkey; Option = '-ToggleHotkey'
       Purpose = 'Read-aloud on/off'; Description = 'Turns Claude Code read-aloud on or off' }
)
$LegacyShortcutNames = @('Claude Vorlesen stoppen.lnk')   # names used by earlier private versions
$SapiByCulture = @{
    'de-DE' = 'Microsoft Hedda Desktop'
    'en-US' = 'Microsoft Zira Desktop'
    'en-GB' = 'Microsoft Hazel Desktop'
}
$TestSentence = @{
    'de' = 'Claude Code kann jetzt vorlesen.'
    'en' = 'Claude Code can now read its answers aloud.'
}

function Write-Step([string]$level, [string]$message) {
    $color = @{ OK = 'Green'; INFO = 'Gray'; WARN = 'Yellow'; ERROR = 'Red' }[$level]
    Write-Host ('[{0}]{1}{2}' -f $level, (' ' * [Math]::Max(1, 7 - $level.Length)), $message) -ForegroundColor $color
}

# Re-indents compressed JSON with two spaces (PowerShell 5.1 formats JSON badly).
function Format-Json([string]$json) {
    $sb = New-Object Text.StringBuilder
    $indent = 0
    $inString = $false
    $escaped = $false
    for ($i = 0; $i -lt $json.Length; $i++) {
        $c = $json[$i]
        if ($inString) {
            [void]$sb.Append($c)
            if ($escaped) { $escaped = $false }
            elseif ($c -eq '\') { $escaped = $true }
            elseif ($c -eq '"') { $inString = $false }
        }
        elseif ($c -eq '"') { $inString = $true; [void]$sb.Append($c) }
        elseif ($c -eq '{' -or $c -eq '[') {
            $close = if ($c -eq '{') { '}' } else { ']' }
            if ($i + 1 -lt $json.Length -and $json[$i + 1] -eq $close) {
                [void]$sb.Append($c).Append($close)
                $i++
            } else {
                $indent++
                [void]$sb.Append($c).Append("`n").Append('  ' * $indent)
            }
        }
        elseif ($c -eq '}' -or $c -eq ']') {
            $indent--
            [void]$sb.Append("`n").Append('  ' * $indent).Append($c)
        }
        elseif ($c -eq ',') { [void]$sb.Append(",`n").Append('  ' * $indent) }
        elseif ($c -eq ':') { [void]$sb.Append(': ') }
        else { [void]$sb.Append($c) }
    }
    return $sb.ToString() + "`n"
}

function Read-Settings([string]$path) {
    if (-not (Test-Path $path)) { return [pscustomobject]@{} }
    $raw = [IO.File]::ReadAllText($path, [Text.Encoding]::UTF8)
    $parsed = $raw | ConvertFrom-Json          # throws on invalid JSON - caller reports it
    if (-not $parsed) { return [pscustomobject]@{} }
    return $parsed
}

function Save-Settings($settings, [string]$path) {
    if (Test-Path $path) {
        $backup = "$path.bak-$(Get-Date -Format 'yyyyMMdd-HHmmss')"
        Copy-Item $path $backup
        Write-Step OK "Backup: $backup"
    }
    $json = $settings | ConvertTo-Json -Depth 100 -Compress
    # PowerShell 5.1 escapes these characters needlessly
    $json = $json -replace '\\u003c', '<' -replace '\\u003e', '>' -replace '\\u0026', '&' -replace '\\u0027', "'"
    [IO.File]::WriteAllText($path, (Format-Json $json), $Utf8NoBom)
    Write-Step OK "Saved: $path"
}

# Returns the full path of a working Python >= 3.9, skipping the Microsoft Store stub.
function Find-Python {
    $ErrorActionPreference = 'Continue'
    foreach ($name in 'python', 'py') {
        foreach ($cmd in @(Get-Command $name -All -ErrorAction SilentlyContinue)) {
            try {
                $ok = & $cmd.Source -c 'import sys; print(sys.version_info >= (3, 9))' 2>$null
                if ($ok -eq 'True') { return (& $cmd.Source -c 'import sys; print(sys.executable)' 2>$null).Trim() }
            } catch { continue }
        }
    }
    return $null
}

# certifi roots + every root Windows trusts (covers TLS-inspecting antivirus and corporate proxies).
function New-CaBundle([string]$python, [string]$path) {
    $ErrorActionPreference = 'Continue'
    $sb = New-Object Text.StringBuilder
    $certifi = (& $python -c 'import pip._vendor.certifi as c; print(c.where())' 2>$null)
    if ($certifi -and (Test-Path $certifi)) { [void]$sb.Append([IO.File]::ReadAllText($certifi).TrimEnd()).Append("`n") }
    $seen = @{}
    foreach ($cert in Get-ChildItem Cert:\LocalMachine\Root, Cert:\CurrentUser\Root) {
        if ($seen.ContainsKey($cert.Thumbprint)) { continue }
        $seen[$cert.Thumbprint] = $true
        [void]$sb.Append("`n# Windows root: $($cert.Thumbprint)`n-----BEGIN CERTIFICATE-----`n")
        [void]$sb.Append([Convert]::ToBase64String($cert.RawData, 'InsertLineBreaks').Replace("`r", ''))
        [void]$sb.Append("`n-----END CERTIFICATE-----`n")
    }
    [IO.File]::WriteAllText($path, $sb.ToString(), $Utf8NoBom)
    return $seen.Count
}

function Invoke-Mp3([string]$path) {
    Add-Type -AssemblyName PresentationCore
    $player = New-Object System.Windows.Media.MediaPlayer
    $player.Open([Uri]$path)
    $clock = [Diagnostics.Stopwatch]::StartNew()
    while (-not $player.NaturalDuration.HasTimeSpan -and $clock.Elapsed.TotalSeconds -lt 5) { Start-Sleep -Milliseconds 50 }
    if (-not $player.NaturalDuration.HasTimeSpan) { $player.Close(); return }
    $length = $player.NaturalDuration.TimeSpan.TotalSeconds
    $player.Play()
    $clock.Restart()
    while ($player.Position.TotalSeconds -lt ($length - 0.05) -and $clock.Elapsed.TotalSeconds -lt ($length + 2)) { Start-Sleep -Milliseconds 100 }
    $player.Close()
}

function Get-ShortcutPath([string]$name) { Join-Path ([Environment]::GetFolderPath('Programs')) $name }

# True if the shortcut runs the hook script of THIS installation (the Start menu is global,
# the Claude directory is not - never touch a shortcut that belongs to another installation).
function Test-OwnShortcut([string]$path) {
    if (-not (Test-Path $path)) { return $false }
    $own = Join-Path $ClaudeDir "hooks\$HookMarker"
    $arguments = (New-Object -ComObject WScript.Shell).CreateShortcut($path).Arguments
    return $arguments -like "*`"$own`"*"
}

# Removes shortcuts of earlier versions - only if they belong to this installation.
function Remove-LegacyShortcuts {
    foreach ($name in $LegacyShortcutNames) {
        $path = Join-Path ([Environment]::GetFolderPath('Programs')) $name
        if (Test-OwnShortcut $path) {
            Remove-Item $path
            Write-Step OK "Removed old shortcut: $path"
        }
    }
}

# Creates or updates one hotkey shortcut from $Shortcuts; returns the hotkey Windows accepted.
function Set-HotkeyShortcut($spec, [string]$scriptPath) {
    $shell = New-Object -ComObject WScript.Shell
    $linkPath = Get-ShortcutPath $spec.Name
    # other shortcuts with the same hotkey would make Windows pick one at random
    $wantedKey = ($spec.Key -replace '\s', '').ToUpper()
    $normalize = { param($k) (@($k.ToUpper() -split '\+') | Sort-Object) -join '+' }
    $clashes = @(foreach ($folder in [Environment]::GetFolderPath('Programs'), [Environment]::GetFolderPath('CommonPrograms'), [Environment]::GetFolderPath('Desktop')) {
        Get-ChildItem $folder -Filter *.lnk -Recurse -ErrorAction SilentlyContinue |
            Where-Object { $_.FullName -ne $linkPath } |
            Where-Object { $key = $shell.CreateShortcut($_.FullName).Hotkey; $key -and (& $normalize $key) -eq (& $normalize $wantedKey) } |
            ForEach-Object { $_.Name }
    })
    $existed = Test-Path $linkPath
    $link = $shell.CreateShortcut($linkPath)
    $link.TargetPath = Join-Path $env:WINDIR 'System32\WindowsPowerShell\v1.0\powershell.exe'
    $link.Arguments = "-NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File `"$scriptPath`" $($spec.Mode)"
    $link.WindowStyle = 7
    $link.Hotkey = $wantedKey
    $link.Description = $spec.Description
    $link.Save()
    $accepted = $shell.CreateShortcut($linkPath).Hotkey
    if ($accepted) {
        Write-Step OK ("Hotkey {0}: {1} - {2} ({3})" -f $(if ($existed) { 'updated' } else { 'created' }), $accepted, $spec.Purpose, $linkPath)
    } else {
        Write-Step WARN "Hotkey '$($spec.Key)' was not accepted - shortcut created without a hotkey: $linkPath"
    }
    if ($clashes.Count -gt 0) {
        Write-Step WARN "$($spec.Key) is already used by: $($clashes -join ', ') - pick another one with $($spec.Option)."
    }
    return $accepted
}

function Invoke-Uninstall {
    Write-Host ''
    Write-Host 'claude-code-tts - uninstall' -ForegroundColor Cyan
    Write-Host "Target: $ClaudeDir"
    Write-Host ''

    # silence a running speech first (by its recorded PID only)
    $stateDir = Join-Path $env:TEMP 'claude-tts'
    $pidFile = Join-Path $stateDir 'speaker.pid'
    if (Test-Path $pidFile) {
        $speakerPid = Get-Content $pidFile -ErrorAction SilentlyContinue
        if ($speakerPid) {
            Get-Process -Id $speakerPid -ErrorAction SilentlyContinue |
                Where-Object { $_.ProcessName -eq 'powershell' } | Stop-Process -Force -ErrorAction SilentlyContinue
        }
        Remove-Item $pidFile -ErrorAction SilentlyContinue
    }

    $settingsPath = Join-Path $ClaudeDir 'settings.json'
    try { $settings = Read-Settings $settingsPath } catch {
        Write-Step ERROR "$settingsPath is not valid JSON - hooks not removed. Fix the file and run again."
        return
    }
    $changed = $false
    if ($settings.PSObject.Properties['hooks'] -and $settings.hooks) {
        foreach ($event in @($settings.hooks.PSObject.Properties.Name)) {
            $kept = @()
            foreach ($entry in @($settings.hooks.$event)) {
                $inner = @($entry.hooks)
                $other = @($inner | Where-Object { $_.command -notlike "*$HookMarker*" })
                if ($other.Count -eq $inner.Count) { $kept += $entry; continue }
                $changed = $true
                if ($other.Count -gt 0) { $entry.hooks = $other; $kept += $entry }
            }
            if ($kept.Count -gt 0) { $settings.hooks.$event = $kept }
            else { $settings.hooks.PSObject.Properties.Remove($event) }
        }
        if (@($settings.hooks.PSObject.Properties).Count -eq 0) { $settings.PSObject.Properties.Remove('hooks') }
    }
    if ($changed) {
        Save-Settings $settings $settingsPath
        Write-Step OK 'Hooks removed from settings.json'
    } else {
        Write-Step INFO 'No read-aloud hooks found in settings.json'
    }

    $ttsDir = Join-Path $ClaudeDir 'tts'
    $files = @(
        (Join-Path $ClaudeDir "hooks\$HookMarker"),
        (Join-Path $ttsDir 'edge_say.py'),
        (Join-Path $ttsDir 'ca-bundle.pem'),
        (Join-Path $ttsDir 'python-path.txt'),
        (Join-Path $ttsDir 'voice.json'),
        (Join-Path $ClaudeDir 'tts-off'),
        (Join-Path $stateDir 'last.txt')    # text of the last answer, kept for replay
    )
    foreach ($file in $files) {
        if (Test-Path $file) { Remove-Item $file; Write-Step OK "Removed: $file" }
    }
    foreach ($spec in $Shortcuts) {
        $shortcut = Get-ShortcutPath $spec.Name
        if (Test-OwnShortcut $shortcut) { Remove-Item $shortcut; Write-Step OK "Removed: $shortcut" }
        elseif (Test-Path $shortcut) { Write-Step INFO "Kept $shortcut - it belongs to another installation." }
    }
    Remove-LegacyShortcuts
    if ((Test-Path $ttsDir) -and -not (Get-ChildItem $ttsDir -Force)) { Remove-Item $ttsDir; Write-Step OK "Removed: $ttsDir" }

    Write-Host ''
    Write-Host 'Done. Restart Claude Code (or open /hooks once) so the hooks are unloaded.' -ForegroundColor Cyan
    Write-Host 'The Python package stays installed; remove it with: python -m pip uninstall edge-tts'
}

function Invoke-Install {
    Write-Host ''
    Write-Host 'claude-code-tts - Claude Code reads its answers aloud' -ForegroundColor Cyan
    Write-Host "Target: $ClaudeDir"
    Write-Host ''

    # 1. Voices
    Add-Type -AssemblyName System.Speech
    $synth = New-Object System.Speech.Synthesis.SpeechSynthesizer
    $installed = @($synth.GetInstalledVoices() | Where-Object { $_.Enabled } | ForEach-Object { $_.VoiceInfo })

    $edgeVoice = $Voice
    if (-not $edgeVoice) {
        $edgeVoice = if ((Get-UICulture).Name -like 'de*') { 'de-DE-KatjaNeural' } else { 'en-US-AriaNeural' }
    }
    $culture = ($edgeVoice -split '-')[0..1] -join '-'
    $language = ($culture -split '-')[0]

    $sapiVoice = $null
    if ($FallbackVoice) {
        $sapiVoice = $installed | Where-Object { $_.Name -eq $FallbackVoice } | Select-Object -First 1
        if (-not $sapiVoice) { Write-Step WARN "Windows voice '$FallbackVoice' is not installed - picking another one." }
    }
    if (-not $sapiVoice -and $SapiByCulture.ContainsKey($culture)) {
        $sapiVoice = $installed | Where-Object { $_.Name -eq $SapiByCulture[$culture] } | Select-Object -First 1
    }
    if (-not $sapiVoice) { $sapiVoice = $installed | Where-Object { $_.Culture.Name -eq $culture } | Select-Object -First 1 }
    if (-not $sapiVoice) {
        $sapiVoice = $installed | Select-Object -First 1
        Write-Step WARN "No Windows voice for $culture installed - the offline fallback uses $($sapiVoice.Name)."
        Write-Step WARN "Add one under Settings > Time & language > Speech."
    }
    if ($OfflineOnly) {
        Write-Step OK "Voice: $($sapiVoice.Name) (offline only)"
    } else {
        Write-Step OK "Voice: $edgeVoice (online) - fallback: $($sapiVoice.Name) (offline)"
    }

    # 2. Hook script and voice settings
    $hooksDir = Join-Path $ClaudeDir 'hooks'
    $ttsDir = Join-Path $ClaudeDir 'tts'
    New-Item -ItemType Directory -Force $hooksDir, $ttsDir | Out-Null
    $scriptPath = Join-Path $hooksDir $HookMarker
    [IO.File]::WriteAllText($scriptPath, $SpeakScript + "`n", $Utf8NoBom)
    Write-Step OK "Hook script: $scriptPath"

    $engine = if ($OfflineOnly) { 'sapi' } else { 'edge' }
    $voiceConfig = [ordered]@{ engine = $engine; edgeVoice = $edgeVoice; edgeRate = '+0%'; sapiVoice = $sapiVoice.Name; sapiRate = 1 }
    $voicePath = Join-Path $ttsDir 'voice.json'
    [IO.File]::WriteAllText($voicePath, (Format-Json ($voiceConfig | ConvertTo-Json -Compress)), $Utf8NoBom)
    Write-Step OK "Voice settings: $voicePath"

    # 3. Online voice (edge-tts)
    $edgePath = Join-Path $ttsDir 'edge_say.py'
    $onlineMp3 = $null
    if ($OfflineOnly) {
        Write-Step INFO 'Online voice skipped (-OfflineOnly).'
    } else {
        [IO.File]::WriteAllText($edgePath, $EdgeScript + "`n", $Utf8NoBom)
        $python = Find-Python
        if (-not $python) {
            Write-Step WARN 'No Python 3.9+ found - the offline voice reads for now.'
            Write-Step WARN 'For the online voice: install Python from python.org, then run this installer again.'
        } else {
            Write-Step OK "Python: $python"
            [IO.File]::WriteAllText((Join-Path $ttsDir 'python-path.txt'), $python, $Utf8NoBom)

            $bundle = Join-Path $ttsDir 'ca-bundle.pem'
            $rootCount = New-CaBundle $python $bundle
            Write-Step OK "Certificate bundle: $bundle (incl. $rootCount Windows root certificates)"

            $ErrorActionPreference = 'Continue'
            $pipOutput = & $python -m pip install --user --disable-pip-version-check --no-warn-script-location --cert $bundle edge-tts 2>&1
            $pipExit = $LASTEXITCODE
            $ErrorActionPreference = 'Stop'
            if ($pipExit -ne 0) {
                Write-Step WARN 'edge-tts could not be installed - the offline voice reads for now. Last pip messages:'
                $pipOutput | Select-Object -Last 3 | ForEach-Object { Write-Host "         $_" -ForegroundColor Yellow }
            } else {
                Write-Step OK 'edge-tts installed'
                $testDir = Join-Path $env:TEMP 'claude-tts-install'
                New-Item -ItemType Directory -Force $testDir | Out-Null
                $sentence = if ($TestSentence.ContainsKey($language)) { $TestSentence[$language] } else { $TestSentence['en'] }
                [IO.File]::WriteAllText("$testDir\test.txt", $sentence, [Text.Encoding]::UTF8)
                Remove-Item "$testDir\test.mp3" -ErrorAction SilentlyContinue
                $ErrorActionPreference = 'Continue'
                $synthOutput = & $python $edgePath "$testDir\test.txt" "$testDir\test.mp3" $edgeVoice 2>&1
                $ErrorActionPreference = 'Stop'
                $mp3 = Get-Item "$testDir\test.mp3" -ErrorAction SilentlyContinue
                if ($mp3 -and $mp3.Length -gt 0) {
                    Write-Step OK 'Online voice reachable'
                    $onlineMp3 = $mp3.FullName
                } else {
                    Write-Step WARN 'Online voice not reachable (internet/proxy?) - the offline voice steps in. Message:'
                    $synthOutput | Select-Object -Last 2 | ForEach-Object { Write-Host "         $_" -ForegroundColor Yellow }
                }
            }
        }
    }

    # 4. Hooks in settings.json
    $settingsPath = Join-Path $ClaudeDir 'settings.json'
    try { $settings = Read-Settings $settingsPath } catch {
        Write-Step ERROR "$settingsPath is not valid JSON - hooks not added."
        Write-Step ERROR 'Fix the file and run the installer again.'
        return
    }
    if (-not $settings.PSObject.Properties['hooks'] -or -not $settings.hooks) {
        $settings | Add-Member -NotePropertyName hooks -NotePropertyValue ([pscustomobject]@{}) -Force
    }

    $baseCommand = "powershell -NoProfile -ExecutionPolicy Bypass -File `"$scriptPath`""
    $wanted = [ordered]@{
        Stop             = @{ command = $baseCommand; timeout = 15; label = 'read aloud after each answer' }
        UserPromptSubmit = @{ command = "$baseCommand -Stop"; timeout = 10; label = 'stop when you send a message' }
    }
    $changed = $false
    foreach ($event in $wanted.Keys) {
        $existing = @()
        if ($settings.hooks.PSObject.Properties[$event]) { $existing = @($settings.hooks.$event) }
        $present = @($existing | Where-Object { @($_.hooks) | Where-Object { $_.command -like "*$HookMarker*" } })
        if ($present.Count -gt 0) {
            Write-Step OK "$event hook ($($wanted[$event].label)) already present"
            continue
        }
        $entry = [pscustomobject]@{
            matcher = ''
            hooks   = @([pscustomobject]@{ type = 'command'; command = $wanted[$event].command; timeout = $wanted[$event].timeout })
        }
        $settings.hooks | Add-Member -NotePropertyName $event -NotePropertyValue (@($existing) + $entry) -Force
        $changed = $true
        Write-Step OK "$event hook ($($wanted[$event].label)) added"
        if ($existing.Count -gt 0) { Write-Step WARN "$($existing.Count) existing $event hook(s) stay active as well." }
    }
    if ($changed) { Save-Settings $settings $settingsPath }

    # 5. Hotkey shortcuts: Start menu links with a global hotkey (stop, replay, on/off)
    $hotkeys = @()
    if ($NoHotkey) {
        Write-Step INFO 'Hotkeys skipped (-NoHotkey).'
    } else {
        Remove-LegacyShortcuts
        foreach ($spec in $Shortcuts) {
            $accepted = Set-HotkeyShortcut $spec $scriptPath
            if ($accepted) { $hotkeys += '{0}: {1}' -f $spec.Purpose, $accepted }
        }
    }

    # 6. Audible test
    if (-not $NoTest) {
        if ($onlineMp3) {
            Invoke-Mp3 $onlineMp3
        } else {
            $synth.SelectVoice($sapiVoice.Name)
            $synth.Rate = 1
            $synth.Speak($(if ($TestSentence.ContainsKey($language)) { $TestSentence[$language] } else { $TestSentence['en'] }))
        }
    }

    Write-Host ''
    $active = if ($onlineMp3) { "$edgeVoice (offline fallback: $($sapiVoice.Name))" } else { $sapiVoice.Name }
    Write-Host "Done. Reading voice: $active" -ForegroundColor Cyan
    Write-Host 'Last step: open /hooks once in Claude Code, or restart Claude Code.' -ForegroundColor Cyan
    if ($hotkeys.Count -gt 0) {
        Write-Host 'Hotkeys (work in any window, may take ~1 s):'
        $hotkeys | ForEach-Object { Write-Host "  $_" }
    }
    Write-Host "Pause read-aloud without a hotkey: create the file $ClaudeDir\tts-off - delete it to turn speech back on."
}

if ($Uninstall) { Invoke-Uninstall } else { Invoke-Install }

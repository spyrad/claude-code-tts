# claude-code-tts - makes Claude Code read its answers aloud on Windows.
#   Natural online voice (edge-tts) with automatic fallback to an offline Windows voice.
#
# Usage:
#   powershell -NoProfile -ExecutionPolicy Bypass -File install.ps1 [options]
#   & ([scriptblock]::Create((irm https://raw.githubusercontent.com/spyrad/claude-code-tts/main/install.ps1))) [options]
#
# Options:
#   -Voice <name>          edge-tts voice, e.g. en-US-AriaNeural, de-DE-KatjaNeural
#                          (default: picked from the Windows display language)
#   -FallbackVoice <name>  offline Windows voice, e.g. "Microsoft Zira Desktop"
#   -OfflineOnly           Windows voice only - no Python, nothing is sent to an online service
#   -StopHotkey <keys>     global key combination that silences a running speech (default CTRL+ALT+S)
#   -NoHotkey              do not create the stop shortcut
#   -NoTest                no audible test at the end
#   -Uninstall             remove hooks, files and the shortcut again
#
# Safe to run repeatedly: existing entries are detected, all other settings stay
# untouched, and settings.json is backed up before it is changed.
# Generated by build.ps1 - edit src/install-template.ps1, not install.ps1.
param(
    [string]$ClaudeDir = (Join-Path $env:USERPROFILE '.claude'),
    [string]$Voice,
    [string]$FallbackVoice,
    [switch]$OfflineOnly,
    [string]$StopHotkey = 'CTRL+ALT+S',
    [switch]$NoHotkey,
    [switch]$NoTest,
    [switch]$Uninstall
)

$ErrorActionPreference = 'Stop'
